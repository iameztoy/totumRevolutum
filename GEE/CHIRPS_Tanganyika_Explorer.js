/** Resolve an explicit area key; never silently fall back to the whole basin. */
function areaSpec(key) {
  var found = AREA_SPECS.filter(function(s) { return s.key === key; });
  if (!found.length) throw new Error('Unknown polygon/area: ' + key);
  return found[0];
}

/** Derive report metrics from six area sums. Null means no represented area. */
function interpretSums(v) {
  var s = summarizeSums(v.v2_area, v.v3_area, v.area, v.wetter_area);
  if (!s) return null;
  s.mad = v.abs_area / v.area; s.rmsd = Math.sqrt(v.sq_area / v.area);
  s.v2Volume = v.v2_area / 1e12; s.v3Volume = v.v3_area / 1e12;
  s.volumeDifference = (v.v3_area - v.v2_area) / 1e12;
  return s;
}


