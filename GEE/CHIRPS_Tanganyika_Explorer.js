/** Fail visibly if any prepared source is missing or incompatible. */
function checkCatalogMetadata(m) {
  var a=m.annualProperties||{}, e=m.extraProperties||{};
  if (a.explorer_schema!=='chirps-africa-explorer-v1' || a.source_v2!==CONFIG.v2 || a.source_v3!==CONFIG.v3 ||
      a.first_year!==1981 || a.last_year!==2025 || a.dem!=='MERIT/DEM/v1_0_3' || !isNativeGrid(m.annualProjection)) throw new Error('Annual rainfall cache does not match the study.');
  if (e.explorer_schema!==CONFIG.schema || e.weights_sha256!==CONFIG.weightsSHA256 || e.first_year!==1981 ||
      e.last_year!==2025 || e.source_snapshot!=='2026-10-12' || e.source_v2!==CONFIG.v2 || e.source_v3!==CONFIG.v3 || !isNativeGrid(m.extraProjection)) throw new Error('Basin support cache does not match the study.');
  var needed=['valid_months','centre_unit','cell_area_equal_m2','monthly_anomaly_r','monthly_anomaly_sd_ratio'];
  for(var i=1;i<=5;i++) needed.push('unit_'+i+'_area_m2');
  for(var c=1;c<=3;c++) needed.push('catchment_'+c+'_area_m2');
  for(var month=1;month<=12;month++) { var mm=('0'+month).slice(-2); needed.push('v2_m'+mm+'_mm','v3_m'+mm+'_mm'); }
  needed.forEach(function(band) { if(m.extraBands.indexOf(band)<0) throw new Error('Missing supplemental band: '+band); });
  var annualNeeded=['elev_m','region_id','fixed_support'];
  for(var y=1981;y<=2025;y++) annualNeeded.push('v2_'+y,'v3_'+y);
  annualNeeded.forEach(function(band) { if(m.annualBands.indexOf(band)<0) throw new Error('Missing annual band: '+band); });
  var expected=UNIT_KEYS.concat(ORIGINAL_KEYS.slice(0,3)).sort();
  if(JSON.stringify(m.polygonKeys.slice().sort())!==JSON.stringify(expected)) throw new Error('Boundary asset must contain the eight expected features exactly once.');
  return true;
}


