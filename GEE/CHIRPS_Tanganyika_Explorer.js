var SUM_NAMES = ['v2_area','v3_area','area','wetter_area','abs_area','sq_area'];

/** Read frozen inputs lazily. No network operation is performed here. */
function createContext() {
  return {prepared:ee.Image(CONFIG.preparedAsset),extra:ee.Image(CONFIG.supportAsset),
    polygons:ee.FeatureCollection(CONFIG.boundaryAsset),grid:ee.Projection(CONFIG.crs,CONFIG.transform),
    bounds:ee.Geometry.Rectangle(CONFIG.bounds,CONFIG.crs,false),annual:{},periods:{}};
}

/** Mean MERIT height and geographic reference from the original annual cache. */
function getTerrain(ctx) { return ctx.prepared.select(['elev_m','region_id']); }

/** Fractional area for a selected polygon, optionally restricted to its land. */
function getArea(ctx,key,landOnly) {
  var spec = areaSpec(key);
  if (!landOnly && spec.catchment) return ctx.extra.select('catchment_'+spec.catchment+'_area_m2').toDouble();
  var ids = landOnly ? spec.land : spec.units;
  if (!ids.length) return ctx.extra.select('unit_1_area_m2').multiply(0).toDouble();
  return ctx.extra.select(ids.map(function(id) { return 'unit_'+id+'_area_m2'; })).reduce(ee.Reducer.sum()).toDouble();
}

/** Fixed paired 45-year support, identical in every selected period. */
function getSupport(ctx) {
  if (!ctx.support) ctx.support = ctx.prepared.select('fixed_support').eq(1)
    .and(getArea(ctx,'whole',false).gt(0)).and(ctx.extra.select('valid_months').eq(540)).selfMask();
  return ctx.support;
}

/** Elevation comparisons always exclude the two supplied lake polygons. */
function selectedArea(ctx,key,elevation,forceLand) {
  var area = getArea(ctx,key,forceLand || elevation !== null).rename('area_m2').updateMask(getSupport(ctx));
  if (elevation !== null) area = area.updateMask(getElevationClasses(ctx).eq(elevation));
  return area.updateMask(area.gt(0));
}

/** Selected annual climatology and fixed-record diagnostic map bands. */
function comparisonImage(ctx,first,last,key,elevation,threshold,forceLand) {
  var pair = getPeriod(ctx,first,last), x = pair.select('v2_mm');
  var delta = pair.select('v3_mm').subtract(x).rename('difference_mm');
  var reference = getPeriod(ctx,1981,2025).select('v2_mm');
  var percent = delta.divide(x).multiply(100).rename('relative_pct')
    .updateMask(reference.gte(threshold).and(x.gt(0)));
  var area = selectedArea(ctx,key,elevation,forceLand);
  return pair.addBands(delta).addBands(percent).addBands(area).addBands(getTerrain(ctx))
    .addBands(getElevationClasses(ctx)).addBands(ctx.extra.select([
      'centre_unit','cell_area_equal_m2','monthly_anomaly_r','monthly_anomaly_sd_ratio']))
    .updateMask(area.gt(0)).reproject(ctx.grid);
}

/** Multiply values by area once. No second polygon-boundary weighting follows. */
function weightedBands(image) {
  var area = image.select('area_m2'), delta = image.select('difference_mm');
  return image.select('v2_mm').multiply(area).rename('v2_area')
    .addBands(image.select('v3_mm').multiply(area).rename('v3_area'))
    .addBands(area.rename('area')).addBands(delta.gt(0).multiply(area).rename('wetter_area'))
    .addBands(delta.abs().multiply(area).rename('abs_area'))
    .addBands(delta.pow(2).multiply(area).rename('sq_area'));
}

/** Six explicit sums on the exact rainfall grid over a containing rectangle. */
function areaSummary(ctx,image) {
  return weightedBands(image).reduceRegion(reductionOptions(ctx,ee.Reducer.sum().unweighted()));
}

/** Five polygon summaries in one reduction; boundary cells can have several fractions. */
function polygonSummary(ctx,first,last,keys,elevation,threshold) {
  var bands = keys.map(function(key) {
    return weightedBands(comparisonImage(ctx,first,last,key,elevation,threshold,false))
      .rename(SUM_NAMES.map(function(name) { return key+'__'+name; }));
  });
  return ee.Image.cat(bands).reduceRegion(reductionOptions(ctx,ee.Reducer.sum().unweighted()));
}

/** All elevation bands within the selected polygon's land, with the same area formula. */
function elevationSummary(ctx,first,last,key,threshold) {
  var image = comparisonImage(ctx,first,last,key,null,threshold,true);
  return weightedBands(image).addBands(image.select('elevation_class')).reduceRegion(
    reductionOptions(ctx,ee.Reducer.sum().unweighted().repeat(6).group({groupField:6,groupName:'class_id'})));
}

/** Area-weighted annual history, all 45 years on the current fixed spatial selection. */
function areaHistory(ctx,key,elevation) {
  var area = selectedArea(ctx,key,elevation,false), bands = [];
  for (var year=1981;year<=2025;year++) bands.push(getAnnual(ctx,year).multiply(area).rename(['v2_'+year,'v3_'+year]));
  return ee.Image.cat(bands).addBands(area.rename('area')).reduceRegion(
    reductionOptions(ctx,ee.Reducer.sum().unweighted()));
}

/** Monthly means are the frozen 1981–2025 climatology, independent of selected years. */
function monthlySummary(ctx,key,elevation) {
  var area = selectedArea(ctx,key,elevation,false), names = [];
  for (var m=1;m<=12;m++) { var mm=('0'+m).slice(-2); names.push('v2_m'+mm+'_mm','v3_m'+mm+'_mm'); }
  return ctx.extra.select(names).multiply(area).addBands(area.rename('area'))
    .reduceRegion(reductionOptions(ctx,ee.Reducer.sum().unweighted()));
}

/** Features for display/point containment only; statistics use stored cell areas. */
function selectedFeatures(ctx,key,landOnly) {
  var spec=areaSpec(key), keys=landOnly ? spec.land.map(function(i) { return UNIT_KEYS[i-1]; }) : spec.features;
  return ctx.polygons.filter(ee.Filter.inList('key',keys));
}

/** Reject clicks outside the actual selected polygon, including shoreline cell slivers. */
function inspectSelectedPoint(ctx,image,key,elevation,lon,lat) {
  var point=ee.Geometry.Point([lon,lat],CONFIG.crs);
  return ee.Dictionary(inspectPoint(ctx,image,lon,lat)).set('inside_polygon',
    selectedFeatures(ctx,key,elevation!==null).filterBounds(point).size().gt(0));
}

