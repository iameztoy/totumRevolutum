    panel.add(ui.Thumbnail({image:ee.Image.pixelLonLat().select('longitude'),params:{bbox:[0,0,1,0.1],dimensions:'230x14',min:0,max:1,palette:spec.palette},style:{width:'230px',height:'14px'}}));
